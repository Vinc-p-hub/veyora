const LanguageContext = createContext(null);
const STORAGE_KEY = "veyro_lang_v1";

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved && DICT[saved] ? saved : "en";
  });

  const setLang = (code) => {
    if (DICT[code]) {
      setLangState(code);
      localStorage.setItem(STORAGE_KEY, code);
    }
  };

  // RTL layout for Arabic, LTR otherwise — applied on <html> so the whole app flips.
  useEffect(() => {
    const meta = LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0];
    document.documentElement.lang = lang;
    document.documentElement.dir = meta.dir;
  }, [lang]);

  const t = useCallback(
    (key, vars) => {
      let str = (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) str = str.split(`{${k}}`).join(String(v));
      }
      return str;
    },
    [lang]
  );

  const tCat = useCallback((category) => t(`cat.${category}`), [t]);

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, tCat, languages: LANGUAGES, isRTL: lang === "ar" }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLang() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLang must be used within LanguageProvider");
  return ctx;
}