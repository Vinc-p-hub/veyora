#!/usr/bin/env python3
"""Generate the Supabase (Postgres) schema + RLS policies from base44/entities/*.jsonc.
Usage: python3 scripts/gen-supabase-schema.py > supabase/migrations/20261010000000_entities.sql
"""
import re, json, glob, os

ROOT = os.path.join(os.path.dirname(__file__), "..", "base44", "entities")
SKIP = {"User"}  # users live in auth.users + public.profiles
REALTIME = {"Order", "Product", "CrawlerJob", "CrawlerSource", "PspWebhookEvent", "WishlistItem"}

def snake(n): return re.sub(r"(?<!^)(?=[A-Z])", "_", n).lower()
def table(n):
    s = snake(n)
    return (s[:-1] + "ies") if s.endswith("y") else s + "s"

def col_type(p):
    t, f = p.get("type"), p.get("format")
    if t == "number": return "numeric"
    if t == "integer": return "bigint"
    if t == "boolean": return "boolean"
    if t in ("array", "object"): return "jsonb"
    if t == "string" and f == "date-time": return "timestamptz"
    return "text"

def lit(v):
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

def default(p):
    if "default" not in p: return ""
    d = p["default"]
    t = col_type(p)
    if t == "jsonb": return f" default {lit(json.dumps(d))}::jsonb"
    if t == "timestamptz": return ""
    return f" default {lit(d)}"

def expr(rule):
    """Translate a Base44 RLS rule into a SQL boolean expression."""
    if rule is False: return "false"
    if rule == {} or rule is True: return "true"
    parts = []
    for k, v in rule.items():
        if k == "$or": parts.append("(" + " or ".join(expr(x) for x in v) + ")")
        elif k == "$and": parts.append("(" + " and ".join(expr(x) for x in v) + ")")
        elif k == "user_condition":
            assert v == {"role": "admin"}, v
            parts.append("public.is_admin()")
        elif k == "created_by_id":
            assert v == "{{user.id}}"; parts.append("created_by_id = auth.uid()::text")
        else:
            c = k[5:] if k.startswith("data.") else k
            assert re.fullmatch(r"[a-z_]+", c), c
            if v == "{{user.email}}":
                parts.append(f"lower({c}) = lower(coalesce(auth.jwt()->>'email',''))")
            elif v == "{{user.id}}":
                parts.append(f"{c} = auth.uid()::text")
            else:
                parts.append(f"{c} = {lit(v)}")
    return "(" + " and ".join(parts) + ")" if parts else "true"

out = ["-- GENERATED by scripts/gen-supabase-schema.py from base44/entities/*.jsonc — do not edit by hand.\n"]
out.append("""create table if not exists public._entity_base (
  id text primary key default gen_random_uuid()::text,
  created_date timestamptz not null default now(),
  updated_date timestamptz not null default now(),
  created_by text,
  created_by_id text
);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;
grant execute on function public.is_admin() to anon, authenticated;

create or replace function public.entity_before_write() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    if coalesce(auth.role(), '') <> 'service_role' then
      new.created_by_id := auth.uid()::text;
      new.created_by := auth.jwt()->>'email';
    end if;
    new.created_date := coalesce(new.created_date, now());
  else
    new.created_by_id := old.created_by_id;
    new.created_by := old.created_by;
    new.created_date := old.created_date;
  end if;
  new.updated_date := now();
  return new;
end $$;
revoke execute on function public.entity_before_write() from public, anon, authenticated;

-- Helper: RLS + audit trigger + one policy per operation (empty expression = operation denied).
create or replace function public._mk_entity(t text, r text, c text, u text, d text, rt boolean) returns void
language plpgsql as $f$
begin
  execute format('alter table public.%I enable row level security', t);
  execute format('drop trigger if exists %I on public.%I', t||'_write', t);
  execute format('create trigger %I before insert or update on public.%I for each row execute function public.entity_before_write()', t||'_write', t);
  execute format('drop policy if exists %I on public.%I', t||'_read', t);
  execute format('drop policy if exists %I on public.%I', t||'_create', t);
  execute format('drop policy if exists %I on public.%I', t||'_update', t);
  execute format('drop policy if exists %I on public.%I', t||'_delete', t);
  if r <> '' then execute format('create policy %I on public.%I for select to anon, authenticated using (%s)', t||'_read', t, r); end if;
  if c <> '' then execute format('create policy %I on public.%I for insert to anon, authenticated with check (%s)', t||'_create', t, c); end if;
  if u <> '' then execute format('create policy %I on public.%I for update to anon, authenticated using (%s) with check (%s)', t||'_update', t, u, u); end if;
  if d <> '' then execute format('create policy %I on public.%I for delete to anon, authenticated using (%s)', t||'_delete', t, d); end if;
  if rt then
    begin execute format('alter publication supabase_realtime add table public.%I', t);
    exception when duplicate_object then null; end;
  end if;
end $f$;
revoke execute on function public._mk_entity(text,text,text,text,text,boolean) from public, anon, authenticated;
""")

for f in sorted(glob.glob(os.path.join(ROOT, "*.jsonc"))):
    d = json.loads(re.sub(r"^\s*//.*$", "", open(f).read(), flags=re.M))
    name = d["name"]
    if name in SKIP: continue
    t = table(name)
    cols = ["  like public._entity_base including all"]
    for k, p in d["properties"].items():
        assert re.fullmatch(r"[a-z_0-9]+", k), (name, k)
        if k in ("id", "created_date", "updated_date", "created_by", "created_by_id"): continue
        if name == "Order" and k == "status": p = {**p, "default": "PENDING_PAYMENT"}  # never default to PAID
        cols.append(f"  {k} {col_type(p)}{default(p)}")
    out.append(f"create table if not exists public.{t} (\n" + ",\n".join(cols) + "\n);")
    rls = d.get("rls") or {}
    ex = {}
    for op in ("read", "create", "update", "delete"):
        rule = rls.get(op, False if rls else True)  # no rls block => open (Base44 default)
        e = expr(rule)
        if op == "create" and name == "Order" and rule is not False:
            e = f"({e}) and status = 'PENDING_PAYMENT'"  # hardening: clients can never create a PAID order
        ex[op] = "" if rule is False else e
    q = lambda x: "'" + x.replace("'", "''") + "'"
    out.append(f"select public._mk_entity('{t}',{q(ex['read'])},{q(ex['create'])},{q(ex['update'])},{q(ex['delete'])},{'true' if name in REALTIME else 'false'});\n")

out.append("drop table public._entity_base;")
print("\n".join(out))
